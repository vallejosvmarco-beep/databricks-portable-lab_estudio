-- =============================================================
-- PLATA ANALISIS - completitud del periodo seleccionado
-- Mantiene la metodologia original: rango observado MIN(FECHA)..MAX(FECHA)
-- por NISE/OPERACION, pero restringido al periodo solicitado.
-- =============================================================

CREATE OR REFRESH MATERIALIZED VIEW ${project.catalog}.${project.schema_analisis}.plata_carga_completitud
AS
WITH base AS (
  SELECT
    CAST(NISE AS STRING) AS NISE,
    CAST(OPERACION AS STRING) AS OPERACION,
    CAST(FECHA_LECTURA_REAL AS TIMESTAMP) AS FECHA_LECTURA,
    CAST(FECHA_LECTURA_REAL AS DATE) AS FECHA,
    HOUR(CAST(FECHA_LECTURA_REAL AS TIMESTAMP)) AS HORA,
    CAST(ENERGIA AS DOUBLE) AS ENERGIA,
    CAST(DEMANDA AS DOUBLE) AS DEMANDA
  FROM ${project.catalog}.${project.schema_plata}.plata_carga
  WHERE NISE IS NOT NULL
    AND OPERACION IS NOT NULL
    AND FECHA_LECTURA_REAL IS NOT NULL
    AND (DEMANDA IS NOT NULL OR ENERGIA IS NOT NULL)
    AND CAST(FECHA_LECTURA_REAL AS TIMESTAMP) >= CAST('${project.periodo_inicio}' AS TIMESTAMP)
    AND CAST(FECHA_LECTURA_REAL AS TIMESTAMP) < CAST(DATE_ADD('${project.periodo_fin}', 1) AS TIMESTAMP)
),
dedup_rank AS (
  SELECT
    b.*,
    ROW_NUMBER() OVER (
      PARTITION BY b.NISE, b.OPERACION, b.FECHA, b.FECHA_LECTURA
      ORDER BY b.DEMANDA DESC NULLS LAST, b.ENERGIA DESC NULLS LAST
    ) AS dup_rn,
    COUNT(*) OVER (
      PARTITION BY b.NISE, b.OPERACION, b.FECHA, b.FECHA_LECTURA
    ) AS dup_group_count
  FROM base b
),
lecturas AS (
  SELECT
    *,
    CASE WHEN dup_group_count > 1 THEN dup_group_count - 1 ELSE 0 END AS duplicados_en_grupo
  FROM dedup_rank
  WHERE dup_rn = 1
),
rangos AS (
  SELECT
    NISE,
    OPERACION,
    MIN(FECHA) AS FECHA_MIN,
    MAX(FECHA) AS FECHA_MAX,
    DATEDIFF(MAX(FECHA), MIN(FECHA)) + 1 AS DIAS_RANGO
  FROM lecturas
  GROUP BY NISE, OPERACION
),
general AS (
  SELECT
    r.NISE,
    r.OPERACION,
    r.FECHA_MIN,
    r.FECHA_MAX,
    r.DIAS_RANGO,
    COUNT(DISTINCT l.FECHA) AS DIAS_CON_AL_MENOS_UN_DATO,
    CAST(r.DIAS_RANGO * 96 AS BIGINT) AS DATOS_ESPERADOS_GENERAL,
    CAST(COUNT(*) AS BIGINT) AS DATOS_PRESENTES_GENERAL,
    ROUND(100.0 * COUNT(*) / NULLIF(r.DIAS_RANGO * 96, 0), 2) AS PCT_COMPLETITUD_GENERAL
  FROM rangos r
  INNER JOIN lecturas l
    ON r.NISE = l.NISE AND r.OPERACION = l.OPERACION
  GROUP BY r.NISE, r.OPERACION, r.FECHA_MIN, r.FECHA_MAX, r.DIAS_RANGO
),
por_hora AS (
  SELECT
    r.NISE,
    r.OPERACION,
    l.HORA,
    r.FECHA_MIN,
    r.FECHA_MAX,
    r.DIAS_RANGO,
    COUNT(DISTINCT l.FECHA) AS DIAS_CON_AL_MENOS_UN_DATO_HORA,
    CAST(r.DIAS_RANGO * 4 AS BIGINT) AS DATOS_ESPERADOS_HORA,
    CAST(COUNT(*) AS BIGINT) AS DATOS_PRESENTES_HORA,
    ROUND(100.0 * COUNT(*) / NULLIF(r.DIAS_RANGO * 4, 0), 2) AS PCT_COMPLETITUD_HORA
  FROM rangos r
  INNER JOIN lecturas l
    ON r.NISE = l.NISE AND r.OPERACION = l.OPERACION
  GROUP BY r.NISE, r.OPERACION, l.HORA, r.FECHA_MIN, r.FECHA_MAX, r.DIAS_RANGO
)
SELECT
  l.NISE,
  l.OPERACION,
  l.FECHA_LECTURA,
  l.FECHA,
  l.HORA,
  l.ENERGIA,
  l.DEMANDA,
  l.dup_group_count AS FILAS_EN_GRUPO_ORIGINAL,
  l.duplicados_en_grupo AS DUPLICADOS_ELIMINADOS_GRUPO,
  g.FECHA_MIN,
  g.FECHA_MAX,
  g.DIAS_RANGO,
  g.DIAS_CON_AL_MENOS_UN_DATO,
  g.DATOS_ESPERADOS_GENERAL,
  g.DATOS_PRESENTES_GENERAL,
  g.PCT_COMPLETITUD_GENERAL,
  h.DIAS_CON_AL_MENOS_UN_DATO_HORA,
  h.DATOS_ESPERADOS_HORA,
  h.DATOS_PRESENTES_HORA,
  h.PCT_COMPLETITUD_HORA,
  CAST(g.DATOS_ESPERADOS_GENERAL - g.DATOS_PRESENTES_GENERAL AS BIGINT) AS DATOS_FALTANTES_GENERAL,
  ROUND(100.0 - LEAST(g.PCT_COMPLETITUD_GENERAL, 100.0), 2) AS PCT_FALTANTES_GENERAL,
  CAST(h.DATOS_ESPERADOS_HORA - h.DATOS_PRESENTES_HORA AS BIGINT) AS DATOS_FALTANTES_HORA,
  ROUND(100.0 - LEAST(h.PCT_COMPLETITUD_HORA, 100.0), 2) AS PCT_FALTANTES_HORA,
  CASE WHEN g.PCT_COMPLETITUD_GENERAL >= 95.0 THEN 1 ELSE 0 END AS FLAG_COMPLETITUD_GENERAL_95,
  CASE WHEN h.PCT_COMPLETITUD_HORA >= 95.0 THEN 1 ELSE 0 END AS FLAG_COMPLETITUD_HORA_95
FROM lecturas l
LEFT JOIN general g
  ON l.NISE = g.NISE AND l.OPERACION = g.OPERACION
LEFT JOIN por_hora h
  ON l.NISE = h.NISE AND l.OPERACION = h.OPERACION AND l.HORA = h.HORA;
