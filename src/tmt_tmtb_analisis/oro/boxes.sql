-- =============================================================
-- ORO - BOXES
-- Fuente UNICA: plata_analisis.plata_950_carga
-- El periodo proviene de project.periodo_inicio / project.periodo_fin.
-- =============================================================

CREATE TEMPORARY VIEW carga_base_completa AS
WITH normalizada AS (
  SELECT
    CAST(NISE AS STRING) AS NISE,
    CAST(PLAN AS STRING) AS PLAN,
    CAST(OPERACION AS STRING) AS OPERACION,
    CAST(FECHA_LECTURA AS TIMESTAMP) AS FECHA_LECTURA,
    CAST(ENERGIA AS DOUBLE) AS ENERGIA,
    CAST(DEMANDA AS DOUBLE) AS DEMANDA,
    CAST(FECHA_LECTURA AS DATE) AS FECHA,
    YEAR(FECHA_LECTURA) AS ANIO,
    MONTH(FECHA_LECTURA) AS MES,
    HOUR(FECHA_LECTURA) AS HORA,
    MINUTE(FECHA_LECTURA) AS MINUTO,
    CASE
      WHEN DAYOFWEEK(FECHA_LECTURA) IN (1, 7) THEN 'FIN_DE_SEMANA'
      ELSE 'ENTRE_SEMANA'
    END AS TIPO_DIA,
    CASE
      WHEN MONTH(FECHA_LECTURA) BETWEEN 5 AND 11 THEN 'PERIODO_LLUVIOSO'
      ELSE 'PERIODO_SECO'
    END AS PERIODO_CLIMATICO
  FROM ${project.catalog}.${project.schema_analisis}.plata_950_carga
  WHERE NISE IS NOT NULL
    AND OPERACION IS NOT NULL
    AND FECHA_LECTURA IS NOT NULL
    AND CAST(FECHA_LECTURA AS DATE) >= CAST('${project.periodo_inicio}' AS DATE)
    AND CAST(FECHA_LECTURA AS DATE) <= CAST('${project.periodo_fin}' AS DATE)
    AND (ENERGIA IS NOT NULL OR DEMANDA IS NOT NULL)
),
conteo_dia AS (
  SELECT
    *,
    COUNT(*) OVER (PARTITION BY NISE, OPERACION, FECHA) AS LECTURAS_DIA
  FROM normalizada
)
SELECT
  NISE, PLAN, OPERACION, FECHA_LECTURA, FECHA, ANIO, MES, HORA, MINUTO,
  TIPO_DIA, PERIODO_CLIMATICO, ENERGIA, DEMANDA, LECTURAS_DIA
FROM conteo_dia
WHERE LECTURAS_DIA = 96;

CREATE TEMPORARY VIEW carga_long_15m AS
SELECT
  NISE, PLAN, OPERACION, FECHA_LECTURA, FECHA, ANIO, MES, HORA, MINUTO,
  TIPO_DIA, PERIODO_CLIMATICO, METRICA, VALOR
FROM carga_base_completa
LATERAL VIEW STACK(2, 'ENERGIA', ENERGIA, 'DEMANDA', DEMANDA) s AS METRICA, VALOR
WHERE VALOR IS NOT NULL;

CREATE TEMPORARY VIEW carga_hora AS
SELECT
  NISE,
  ANY_VALUE(PLAN) AS PLAN,
  OPERACION,
  FECHA,
  ANIO,
  MES,
  HORA,
  TIPO_DIA,
  PERIODO_CLIMATICO,
  METRICA,
  CASE
    WHEN METRICA = 'ENERGIA' THEN SUM(VALOR)
    WHEN METRICA = 'DEMANDA' THEN AVG(VALOR)
  END AS VALOR,
  COUNT(*) AS BLOQUES_15M_PRESENTES
FROM carga_long_15m
GROUP BY NISE, OPERACION, FECHA, ANIO, MES, HORA, TIPO_DIA, PERIODO_CLIMATICO, METRICA
HAVING COUNT(*) = 4;

-- ============================================================
-- 1) BOXES ANUAL
-- En la configuracion inicial ANIO=2026, pero la muestra contiene solo junio 2026.
-- ============================================================
CREATE OR REFRESH MATERIALIZED VIEW ${project.catalog}.${project.schema_oro}.boxes_anual AS
WITH cuartiles AS (
  SELECT
    NISE, ANY_VALUE(PLAN) AS PLAN, OPERACION, ANIO, HORA, METRICA,
    PERCENTILE_APPROX(VALOR, 0.25, 10000) AS Q1,
    PERCENTILE_APPROX(VALOR, 0.50, 10000) AS Q2,
    PERCENTILE_APPROX(VALOR, 0.75, 10000) AS Q3,
    AVG(VALOR) AS MEDIA,
    COUNT(*) AS N
  FROM carga_hora
  GROUP BY NISE, OPERACION, ANIO, HORA, METRICA
),
datos_etiquetados AS (
  SELECT
    l.NISE, l.PLAN, l.OPERACION, l.ANIO, l.HORA, l.METRICA, l.VALOR,
    q.Q1, q.Q2, q.Q3, q.MEDIA, q.N,
    q.Q3 - q.Q1 AS IQR,
    q.Q1 - 1.5 * (q.Q3 - q.Q1) AS LOWER_FENCE,
    q.Q3 + 1.5 * (q.Q3 - q.Q1) AS UPPER_FENCE
  FROM carga_hora l
  JOIN cuartiles q
    ON l.NISE = q.NISE
   AND l.OPERACION = q.OPERACION
   AND l.ANIO = q.ANIO
   AND l.HORA = q.HORA
   AND l.METRICA = q.METRICA
)
SELECT
  NISE, ANY_VALUE(PLAN) AS PLAN, OPERACION, ANIO, HORA, METRICA,
  Q1, Q2, Q3, IQR, LOWER_FENCE, UPPER_FENCE,
  MIN(CASE WHEN VALOR BETWEEN LOWER_FENCE AND UPPER_FENCE THEN VALOR END) AS WHISKER_MIN,
  MAX(CASE WHEN VALOR BETWEEN LOWER_FENCE AND UPPER_FENCE THEN VALOR END) AS WHISKER_MAX,
  MEDIA, N,
  SUM(CASE WHEN VALOR < LOWER_FENCE OR VALOR > UPPER_FENCE THEN 1 ELSE 0 END) AS OUTLIERS_COUNT
FROM datos_etiquetados
GROUP BY NISE, OPERACION, ANIO, HORA, METRICA, Q1, Q2, Q3, IQR, LOWER_FENCE, UPPER_FENCE, MEDIA, N;

